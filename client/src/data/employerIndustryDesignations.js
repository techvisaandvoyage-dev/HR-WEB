/**
 * Get designations for a given industry
 * @param {string} industry
 * @returns {Array<{value: string, label: string}>}
 */
export const getDesignationsForIndustry = (industry) => {
  const designations = EMPLOYER_INDUSTRY_DESIGNATIONS[industry] || EMPLOYER_INDUSTRY_DESIGNATIONS['Other'];
  return designations.map((d) => ({ value: d, label: d }));
};
