export const formatPhoneWithCountryCode = (phone, countryCode = '+91') => {
  if (!phone) return '';
  const clean = String(phone).trim();
  if (!clean) return '';
  if (clean.startsWith('+')) return clean;
  if (clean.startsWith('00')) return `+${clean.slice(2)}`;
  const cc = countryCode && String(countryCode).trim() ? String(countryCode).trim() : '+91';
  return `${cc} ${clean}`;
};
